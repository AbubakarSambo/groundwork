/**
 * WHAT A PIECE OF EVIDENCE ACTUALLY PROVES, SAID IN WORDS A PERSON READS.
 *
 * The single most dangerous thing this feature could do is let a report say "the evidence shows he
 * visited the shop" when what exists is a calendar entry. Three claims are involved and they are
 * not the same:
 *
 *   somebody was at the shop
 *   a conversation happened
 *   a meaningful conversation happened
 *
 * Nothing that can be ingested proves the third, and most of what can be ingested does not prove
 * the second. So the sentence is generated from the kind and the strength rather than written by a
 * model, and the model is given the sentence rather than the raw record.
 *
 * THE PERSON'S OWN ACCOUNT IS EVIDENCE TOO, and saying so matters. `SELF_REPORTED` is not a
 * suspicion - most of what any check-in knows is self-reported and always has been. It is simply
 * not corroboration, and the difference is worth stating plainly rather than implying.
 */

export type Kind =
  | 'VISIT' | 'CALL' | 'MESSAGE' | 'MEETING' | 'PROPOSAL' | 'TRANSACTION'
  /* Technical work. The same problem as a customer visit, and it was not asked about for longer. */
  | 'MERGE' | 'TEST_RUN' | 'DEPLOY' | 'RELEASE' | 'INCIDENT';
export type Strength = 'COMPLETED' | 'RECORDED' | 'ARRANGED' | 'SELF_REPORTED';

const THING: Record<Kind, string> = {
  VISIT: 'a visit',
  CALL: 'a call',
  MESSAGE: 'a message',
  MEETING: 'a meeting',
  PROPOSAL: 'a proposal',
  TRANSACTION: 'a transaction',
  /*
   * NAMED FOR WHAT HAPPENED, NEVER FOR WHAT IT MEANS. "a deployment" and not "a release to users";
   * "a test run" and not "the tests passing". The state each one reaches is worked out in
   * what-shipped-actually-means.ts, where the rules about it live, and the moment a name here
   * smuggles in a conclusion those rules are being applied to a lie.
   */
  MERGE: 'a merge',
  TEST_RUN: 'a test run',
  DEPLOY: 'a deployment',
  RELEASE: 'a release',
  INCIDENT: 'an incident',
};

/**
 * One sentence, and it never claims more than the strength allows.
 *
 * `who` and `withWhom` are labels the caller has already resolved - a name never reaches here, for
 * the same reason names never reach a stored report.
 */
/**
 * TECHNICAL RECORDS NEEDED THEIR OWN SENTENCES, AND FINDING OUT WHY WAS THE USEFUL PART.
 *
 * Reusing the conversation wording produced "a deployment was logged... and no evidence of what was
 * said", which is merely odd, and "a test run completed - the one kind of record that shows a thing
 * finished rather than attempted", which is dangerous. A test run COMPLETING is not a test run
 * PASSING. That is precisely the conflation the shipping rules exist to prevent, generated by their
 * own sibling file, and no amount of care downstream survives being handed that sentence.
 *
 * So the two strengths that make an outcome claim are written separately for technical work. The
 * other two are about who is vouching for the record rather than what it contains, and those needed
 * no changing at all.
 */
const TECHNICAL = new Set<Kind>(['MERGE', 'TEST_RUN', 'DEPLOY', 'RELEASE', 'INCIDENT']);

const TECHNICAL_COMPLETED: Partial<Record<Kind, string>> = {
  MERGE: 'a merge that went in. The code is on the branch it was merged to, which is not the same as it running anywhere.',
  TEST_RUN: 'a test run that finished. Finishing is not passing, and passing is not evidence that the tests cover what anybody cares about.',
  DEPLOY: 'a deployment that finished. Something reached an environment, which is not evidence that it works there or that anybody can reach it.',
  RELEASE: 'a release that went out. It is available, which is not the same as it being switched on for anybody or being used.',
  INCIDENT: 'an incident that was closed. It stopped, which is not the same as the cause being found or fixed.',
};

const TECHNICAL_RECORDED: Partial<Record<Kind, string>> = {
  MERGE: 'a merge logged by a system. Good evidence it happened, and no evidence of what the code does.',
  TEST_RUN: 'a test run logged by a system. Evidence it ran. Whether it passed, and what it covers, are separate questions this does not answer.',
  DEPLOY: 'a deployment logged by a system. Evidence something was deployed, and no evidence that it works or that anybody has used it.',
  RELEASE: 'a release logged by a system. Evidence it went out, and no evidence that it is enabled or that it does what it was built for.',
  INCIDENT: 'an incident logged by a system. Evidence something went wrong and was recorded, and no evidence of how it was resolved.',
};

export function whatThisProves(
  kind: Kind,
  strength: Strength,
  who: string,
  withWhom: string | null,
): string {
  const thing = THING[kind];
  const at = withWhom ? ` with ${withWhom}` : '';

  if (TECHNICAL.has(kind) && (strength === 'COMPLETED' || strength === 'RECORDED')) {
    const said = strength === 'COMPLETED' ? TECHNICAL_COMPLETED[kind] : TECHNICAL_RECORDED[kind];
    if (said) return said;
  }

  switch (strength) {
    case 'COMPLETED':
      /* The only strength that is evidence of an outcome rather than of an activity. */
      return `${thing}${at} completed. This is the one kind of record that shows a thing finished rather than that it was attempted.`;

    case 'RECORDED':
      /*
       * A system record is good evidence that somebody was there and no evidence at all of what was
       * said. Saying both halves is the point - the second half is what a reader will otherwise
       * supply for themselves.
       */
      return `${thing}${at} was logged in a system somebody operates. That is evidence it happened, and no evidence of what was said or whether it went anywhere.`;

    case 'ARRANGED':
      /* The trap. A calendar entry is evidence of an intention, and reads as evidence of an event. */
      return `${thing}${at} was arranged. A record that something was scheduled is not a record that it took place, and this one says nothing about whether it did.`;

    case 'SELF_REPORTED':
      return `${who} says ${thing}${at} happened. Their own account, which is most of what any check-in knows - it is not corroboration and does not need to be treated as doubtful.`;
  }
}

/**
 * WHAT NOBODY MAY CONCLUDE FROM ANY OF IT.
 *
 * Given to the synthesis alongside the records. Without it a model reading twelve logged visits and
 * one sale will reach for the sentence that explains the gap, and the record cannot support any
 * such sentence.
 */
export const NEVER_CONCLUDE =
  'WHAT THESE RECORDS CANNOT TELL YOU. None of them says whether a conversation was any good, '
  + 'whether the right person was there, or why something did or did not progress. Counting them is '
  + 'not a measure of how somebody is doing: forty logged visits and two conversations that went '
  + 'anywhere is a different situation from fifteen and ten, and the records alone cannot tell you '
  + 'which is which. Where a record and somebody\'s own account disagree, say both and settle '
  + 'neither. Never write that a record proves somebody did not do something - an unlogged visit and '
  + 'an unmade one look identical from here.';
